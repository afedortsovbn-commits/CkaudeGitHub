import { describe, expect, it } from 'vitest';
import { hintInsertText, parseHint } from './hints';

const BODY = [
  'ОТВЕТ КЛИЕНТУ',
  'Приносим извинения. Подскажите, на какой АЗС это произошло?',
  '',
  'УТОЧНИТЕ У КЛИЕНТА',
  '• № АЗС и область',
  '• № топливной карты (9 цифр)',
  '',
  'ДЕЙСТВИЯ ОПЕРАТОРА',
  '1. Выслушать клиента',
  '2. Передать в ООКК',
  '',
  'ВАЖНО',
  '• Брелоком за пределами РБ заправиться нельзя',
  '',
  'КОНТАКТЫ',
  '• +7 800 777 71 00',
  '',
  'ЕСЛИ НЕ РЕШЕНО — ОБРАЩЕНИЕ НА 2-Ю ЛИНИЮ',
  'Когда: клиент в РБ не может заправиться',
  'Тема: Топливная карта',
  'Подтема: Не может заправиться',
  '',
  'ИСХОДНАЯ ИНСТРУКЦИЯ',
  'Полный текст из документа',
].join('\n');

describe('parseHint', () => {
  it('разбирает разделы структурированной подсказки (заголовки на кириллице)', () => {
    const h = parseHint(BODY);
    expect(h.structured).toBe(true);
    expect(h.answer).toBe('Приносим извинения. Подскажите, на какой АЗС это произошло?');
    expect(h.ask).toEqual(['№ АЗС и область', '№ топливной карты (9 цифр)']);
    expect(h.steps).toEqual(['Выслушать клиента', 'Передать в ООКК']);
    expect(h.warn).toEqual(['Брелоком за пределами РБ заправиться нельзя']);
    expect(h.contacts).toEqual(['+7 800 777 71 00']);
    expect(h.escalate).toEqual({
      when: 'клиент в РБ не может заправиться',
      topic: 'Топливная карта',
      sub: 'Не может заправиться',
    });
    expect(h.source).toBe('Полный текст из документа');
  });

  it('обычная справка без заголовков — текст целиком', () => {
    const h = parseHint('Просто текст справки.\nВторая строка.');
    expect(h.structured).toBe(false);
    expect(h.intro).toBe('Просто текст справки.\nВторая строка.');
    expect(hintInsertText('Просто текст')).toBe('Просто текст');
  });

  it('вставка в ответ — только «Ответ клиенту»', () => {
    expect(hintInsertText(BODY)).toBe('Приносим извинения. Подскажите, на какой АЗС это произошло?');
  });
});
